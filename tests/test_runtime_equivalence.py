def test_fast_clone_shares_no_undeclared_mutable_container():
    """Exhaustive guard: every shared container must be declared shareable.

    A hand-maintained copy list silently rots when a new mutable attribute is
    added to the engine. This walks the real attribute dict instead, so the
    next person to add mutable state gets a failure here rather than a
    counterfactual that quietly writes into the live simulation.
    """
    from collections import deque as _deque

    eng = make_engine(GOLDEN_SCENARIO, seed=GOLDEN_SEED, cfg=CFG)
    for _ in range(4):
        eng.step_interval()
    eng.inject_burst(eng.demands[0].id, 1.5, 30.0)
    cl = eng.fast_clone()

    mutable_types = (np.ndarray, list, dict, set, _deque, bytearray)
    offenders = []
    for name, value in vars(eng).items():
        if not isinstance(value, mutable_types):
            continue
        if vars(cl).get(name) is value and name not in SimulationEngine._SHAREABLE_ATTRS:
            offenders.append(name)
    assert not offenders, (
        f"fast_clone shares undeclared mutable state: {offenders}. Either copy "
        f"it in fast_clone() or add it to _SHAREABLE_ATTRS with a justification.")

    # and everything declared shareable really is shared (else it is dead weight)
    for name in SimulationEngine._SHAREABLE_ATTRS:
        assert vars(cl)[name] is vars(eng)[name], f"{name} declared shareable but copied"


