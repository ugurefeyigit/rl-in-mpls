def build_env(scenario: str = GOLDEN_SCENARIO, seed: int = GOLDEN_SEED) -> MplsTeEnv:
    env = MplsTeEnv(scenario=scenario, base_seed=seed)
    env.reset(options={"episode_seed": seed})
    return env


def golden_action(step: int, n_demands: int, k: int) -> int:
    """The scripted action sequence that produced the goldens.

    Phase A spreads reroutes across every demand and every non-current
    candidate; phase B hammers two demands so cooldown rejections and flap
    detection are both exercised. Changing this invalidates every golden below.
    """
    if step < 12:
        d = step % n_demands
        p = 1 + (step % (k - 1))
    else:
        d = step % 2
        p = 1 + ((step // 2) % (k - 1))
    return 1 + d * k + p


@lru_cache(maxsize=1)
def replay() -> tuple[tuple[dict, ...], dict]:
    """Replay the golden episode once and cache it (all tests read the same run).

    ``action_masks``/``_obs``/``snapshot`` are pure reads, so sampling them only
    at the probe step reproduces exactly what the generator recorded.
    """
    env = build_env()
    eng = env.eng
    records: list[dict] = []
    probe: dict = {}
    for step in range(GOLDEN_N_STEPS):
        action = golden_action(step, env.n_demands, env.k)
        if step == GOLDEN_PROBE_STEP:
            probe = {
                "mask": env.action_masks().copy(),
                "obs": env._obs().copy(),
                "link_load": eng.link_load.copy(),
                "link_util": eng.link_util.copy(),
                "link_qdelay": eng.link_qdelay.copy(),
                "link_loss": eng.link_loss.copy(),
                "util_ewma": eng.util_ewma.copy(),
                "demand_delay": eng.demand_delay.copy(),
                "demand_loss": eng.demand_loss.copy(),
                "demand_volumes": eng.demand_volumes.copy(),
                "demand_sla_ok": eng.demand_sla_ok.copy(),
                "current_path": eng.current_path.copy(),
                "t_min": eng.t_min,
                "snapshot": eng.snapshot(),
            }
        _obs, reward, _term, _trunc, info = env.step(action)
        records.append({
            "action": action,
            "accepted": bool(info["decoded_action"].get("accepted", False)),
            "reward": float(reward),
            "metrics": info["metrics"],
            "rc": info["reward_components"],
            "n_failed": len(info["metrics"]["failed_links"]),
        })
    return tuple(records), probe


def assert_exact(actual, expected, label: str) -> None:
    """Bit-for-bit equality with a diagnostic first-difference message.

    The optimizations in this branch are designed to preserve arithmetic order,
    so every golden below is asserted exactly. A failure here means an
    optimization changed the numerics and must be justified or reverted -- not
    that the golden should be regenerated.
    """
    a = np.asarray(actual, dtype=np.float64).ravel()
    e = np.asarray(expected, dtype=np.float64).ravel()
    assert a.shape == e.shape, f"{label}: shape {a.shape} != expected {e.shape}"
    bad = np.flatnonzero(a != e)
    if bad.size:
        i = int(bad[0])
        raise AssertionError(
            f"{label}: {bad.size}/{a.size} values differ; first at index {i}: "
            f"got {a[i]!r}, expected {e[i]!r} (delta {a[i] - e[i]!r})")


