def test_golden_validate_action_reasons():
    """Not just accept/reject: the *reason* for every action, at every step.

    This pins each individual constraint (same-path, failed link, cooldown,
    protected-class bandwidth) separately, so an optimization that drops one of
    them cannot hide behind another still rejecting the action.
    """
    codes = {"ok": "o", "already on this path": "a",
             "path traverses a failed link": "f",
             "insufficient bandwidth for protected class": "b",
             "unknown demand": "u", "unknown candidate path": "u"}

    def code(reason: str) -> str:
        return "c" if reason.startswith("cooldown until step") else codes[reason]

    env = build_env()
    for step, golden in enumerate(GOLDEN_VALIDATE_REASONS):
        got = "".join(code(env.eng.validate_action(d_idx, p_idx, "rl")[1])
                      for d_idx in range(env.n_demands) for p_idx in range(env.k))
        assert len(got) == env.n_demands * env.k
        assert got == golden, (
            f"step {step}: validate_action reasons changed\n"
            f"  got      {got}\n  expected {golden}")
        env.step(golden_action(step, env.n_demands, env.k))


def test_all_rejection_reasons_are_exercised_by_the_golden_trace():
    """Guard against the goldens silently ceasing to cover a constraint."""
    seen = {c for row in GOLDEN_VALIDATE_REASONS for c in row}
    assert seen >= {"o", "a", "f", "c", "b"}, (
        f"golden trace no longer exercises every constraint; saw {sorted(seen)}")


