def ref_link_loads(eng) -> np.ndarray:
    """Naive scalar accumulation of link load from current placements."""
    loads = np.zeros(eng.topo.n_dlinks)
    for d_idx in range(eng.n_demands):
        if eng.disconnected[d_idx]:
            continue
        vol = float(eng.demand_volumes[d_idx])
        for li in eng._path_links[d_idx][int(eng.current_path[d_idx])]:
            loads[int(li)] += vol
    return loads


def ref_path_available(eng, d_idx: int, p_idx: int) -> bool:
    """Path availability straight from the authoritative ``link_up`` dict."""
    return all(eng.link_up[eng.topo.dlinks[int(li)].undirected_id]
               for li in eng._path_links[d_idx][p_idx])


def ref_masks(env) -> np.ndarray:
    """The mask as the safety filter defines it: one validate_action per action."""
    mask = np.zeros(env.action_space.n, dtype=bool)
    mask[0] = True
    for d_idx in range(env.n_demands):
        n_cands = len(env.eng.demands[d_idx].candidate_paths)
        for p_idx in range(min(env.k, n_cands)):
            ok, _ = env.eng.validate_action(d_idx, p_idx, source="rl")
            mask[1 + d_idx * env.k + p_idx] = ok
    return mask


def ref_projected_loads(eng, d_idx: int, p_idx: int) -> np.ndarray:
    """Remove the demand from its current path, then add it to the candidate."""
    loads = eng.link_load.copy()
    vol = float(eng.demand_volumes[d_idx])
    if not eng.disconnected[d_idx]:
        loads[eng._path_links[d_idx][int(eng.current_path[d_idx])]] -= vol
    loads[eng._path_links[d_idx][p_idx]] += vol
    return loads


def _states_across_episode(n_states: int = 8, scenario: str = GOLDEN_SCENARIO):
    """Yield engines/envs at several distinct points of a scripted episode."""
    env = build_env(scenario)
    for step in range(GOLDEN_N_STEPS):
        if step % max(1, GOLDEN_N_STEPS // n_states) == 0:
            yield step, env
        env.step(golden_action(step, env.n_demands, env.k))
    yield GOLDEN_N_STEPS, env


