def _disconnect_engine():
    """Fail every link used by demand 0's candidates, forcing disconnections."""
    eng = make_engine(GOLDEN_SCENARIO, seed=GOLDEN_SEED, cfg=CFG)
    eng.step_interval()
    link_ids = {eng.topo.dlinks[int(li)].undirected_id
                for p_idx in range(len(eng.demands[0].candidate_paths))
                for li in eng._path_links[0][p_idx]}
    for link_id in sorted(link_ids):
        eng.set_link_state(link_id, False)
    eng.step_interval()
    return eng


def test_disconnected_demands_are_excluded_from_loads_and_lsp_counts():
    """A disconnected demand offers no load and is on no LSP.

    Without this the golden trace never disconnects anything, leaving the
    `disconnected` branches of _compute_tick and snapshot() untested.
    """
    eng = _disconnect_engine()
    assert eng.disconnected.any(), "fixture failed to disconnect any demand"

    assert_exact(eng.link_load, ref_link_loads(eng), "link_load with disconnections")

    snap = eng.snapshot()
    for i, link in enumerate(snap["links"]):
        expected = sum(
            1 for d_idx in range(eng.n_demands)
            if not eng.disconnected[d_idx]
            and i in [int(x) for x in eng._path_links[d_idx][int(eng.current_path[d_idx])]]
        )
        assert link["n_lsps"] == expected, (
            f"n_lsps for link {i} counts disconnected demands")

    for d_idx in range(eng.n_demands):
        if not eng.disconnected[d_idx]:
            continue
        assert eng.demand_delay[d_idx] == 0.0
        assert eng.demand_loss[d_idx] == 1.0
        assert eng.demand_carried[d_idx] == 0.0
        assert not eng.demand_sla_ok[d_idx]
        assert snap["demands"][d_idx]["disconnected"] is True
        assert snap["demands"][d_idx]["carried_mbps"] == 0.0


def test_disconnected_demands_recover_when_links_return():
    """Restoring the links must re-place every disconnected demand via FRR."""
    eng = _disconnect_engine()
