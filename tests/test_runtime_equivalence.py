def test_shared_cached_arrays_are_read_only():
    """Immutable data shared between engines must not be writable through one.

    Any ndarray that two engines hold as the *same object* is a shared cache;
    if it were writable, one engine could corrupt another. Read-only flags make
    that impossible rather than merely unlikely.
    """
    a = make_engine(GOLDEN_SCENARIO, seed=1, cfg=CFG)
    b = make_engine(GOLDEN_SCENARIO, seed=2, cfg=CFG)
    shared: list[str] = []
    for name, va in vars(a).items():
        vb = vars(b).get(name)
        if isinstance(va, np.ndarray) and va is vb:
            shared.append(name)
            assert not va.flags.writeable, (
                f"engine attribute '{name}' is shared between instances but writable")
    for name in shared:
        assert name not in MUTABLE_ARRAY_ATTRS, f"mutable state '{name}' is shared!"


def test_mutable_state_is_never_shared_between_engines():
    a = make_engine(GOLDEN_SCENARIO, seed=1, cfg=CFG)
